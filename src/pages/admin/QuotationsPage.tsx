import { useMemo, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { ReceiptText } from 'lucide-react';
import { useQuotations } from '../../hooks/useData';
import { formatPHP, formatDate } from '../../lib/format';
import { EmptyState, SearchInput, Select, StatusBadge, Table, THead, TH, TR, TD, SectionHeader } from '../../components/ui';
import { QUOTATION_STATUSES } from '../../lib/constants';

export default function AdminQuotations() {
  const { quotations, loading } = useQuotations();
  const navigate = useNavigate();
  const [query, setQuery] = useState('');
  const [status, setStatus] = useState('All');

  const filtered = useMemo(() => {
    const q = query.toLowerCase().trim();
    return quotations.filter((x) => {
      const matchesStatus = status === 'All' || x.status === status;
      return matchesStatus && [x.quotationNumber, x.clientName, x.clientEmail, x.inputs.projectType].join(' ').toLowerCase().includes(q);
    });
  }, [quotations, query, status]);

  return (
    <div className="space-y-6">
      <SectionHeader eyebrow="Quotation" title="Quotations" description="All preliminary estimates generated by the Smart Quotation tools." />

      <div className="flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between">
        <SearchInput value={query} onChange={setQuery} placeholder="Search by number, client…" className="w-full sm:max-w-sm" />
        <Select value={status} onChange={(e) => setStatus(e.target.value)} className="w-full sm:w-44">
          <option value="All">All statuses</option>
          {QUOTATION_STATUSES.map((s) => <option key={s} value={s}>{s}</option>)}
        </Select>
      </div>

      {loading ? (
        <Table><THead><TR><TH>Number</TH><TH>Client</TH><TH>Date</TH><TH>Total</TH><TH>Status</TH></TR></THead></Table>
      ) : filtered.length === 0 ? (
        <EmptyState icon={<ReceiptText size={22} />} title="No quotations found" description="Adjust your filters or wait for new submissions." />
      ) : (
        <Table>
          <THead>
            <TR>
              <TH>Number</TH>
              <TH>Client</TH>
              <TH>Project</TH>
              <TH>Date</TH>
              <TH>Total</TH>
              <TH>Status</TH>
            </TR>
          </THead>
          <tbody>
            {filtered.map((q) => (
              <TR key={q.id} onClick={() => navigate(`/admin/quotations/${q.id}`)}>
                <TD className="font-semibold text-agblue">{q.quotationNumber}</TD>
                <TD>
                  <p className="font-semibold text-agdark-800">{q.clientName}</p>
                  <p className="text-xs text-agdark-400">{q.clientEmail}</p>
                </TD>
                <TD>{q.inputs.projectType}</TD>
                <TD>{formatDate(q.createdAt)}</TD>
                <TD className="font-mono-data font-semibold">{formatPHP(q.totalEstimate)}</TD>
                <TD><StatusBadge status={q.status} /></TD>
              </TR>
            ))}
          </tbody>
        </Table>
      )}
    </div>
  );
}
